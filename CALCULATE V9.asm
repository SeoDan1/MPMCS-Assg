; 		MODE 2: LOGIC
; ==============================
LOGIC_AND:
    MOV A, R3
    ANL A, R5
    MOV R3, A
    MOV R2, #00H
    RET
LOGIC_OR:
    MOV A, R3
    ORL A, R5
    MOV R3, A
    MOV R2, #00H
    RET
LOGIC_XOR:
    MOV A, R3
    XRL A, R5
    MOV R3, A
    MOV R2, #00H
    RET
LOGIC_NOT:
    MOV A, R3
    CPL A
    MOV R3, A
    MOV R2, #00H
    RET

; ==============================
; 		MODE 3: ADVANCE
; ==============================
MATH_SQUARE:
    MOV A, R2
    MOV R4, A
    MOV A, R3
    MOV R5, A
    CLR 20H.2
    LCALL MATH_MUL
    RET

MATH_POWER:
    MOV A, R4
    ORL A, R5
    JNZ POWER_START
    MOV R2, #00H
    MOV R3, #01H
    RET
POWER_START:
    MOV 48H, R2             
    MOV 49H, R3             
POWER_LOOP:
    MOV A, R4
    ORL A, R5
    DEC A
    JZ POWER_DONE
    MOV A, R5
    JNZ P_DEC_L
    DEC R4
P_DEC_L:
    DEC R5
    PUSH 04H
    PUSH 05H
    MOV R4, 48H
    MOV R5, 49H
    LCALL MATH_MUL          
    POP 05H
    POP 04H
    JB 20H.0, POWER_DONE
    SJMP POWER_LOOP
POWER_DONE:
    RET

MATH_SQRT:
    MOV 48H, R2                 ; High byte of input
    MOV 49H, R3                 ; Low byte of input
    
    ; Check if input is zero
    MOV A, 48H
    ORL A, 49H
    JNZ SQRT_START
    MOV R2, #00H
    MOV R3, #00H
    RET

SQRT_START:
    MOV R0, #00H

SQRT_LOOP:
    INC R0
    MOV A, R0
    MOV B, R0
    MUL AB                      ; B = High byte, A = Low byte
    MOV R4, B                   ; R4 = Square High
    MOV R5, A                   ; R5 = Square Low
    
    ; 16-bit subtraction: Target (48H:49H) - Square (R4:R5)
    CLR C
    MOV A, 49H
    SUBB A, R5                  ; Low byte subtract
    MOV A, 48H
    SUBB A, R4                  ; High byte subtract with carry
    JC SQRT_OVERSHOOT           ; Borrow set -> Square > Target
	MOV A, 48H
    XRL A, R4
    JNZ SQRT_LOOP               ; High byte > 0 -> Target > Square, continue
	MOV A, 49H
    XRL A, R5
    JNZ SQRT_LOOP
    SJMP SQRT_EXACT             ; Perfect match!

SQRT_OVERSHOOT:
    DEC R0                      ; Step back to largest integer root
	MOV R2, #00H
	MOV A, R0
    MOV R3, A
    CLR 20H.2
	RET
	
SQRT_EXACT:
    MOV R2, #00H
	MOV A, R0
    MOV R3, A
    CLR 20H.2                   ; Positive result
    RET

; ==============================
; 		ERROR DETECTION
; ==============================
ARITH_OVERFLOW:
    MOV ERROR_CODE, #01H
    LJMP SET_ERROR
DIVIDE_BY_ZERO:
    MOV ERROR_CODE, #03H
    LJMP SET_ERROR
SET_ERROR:
    SETB 20H.0
    RET

