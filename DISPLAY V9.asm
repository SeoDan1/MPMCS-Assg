    MOV R0, #255
READY_D_MIDDLE:
    MOV R1, #255
    DJNZ R1, $
    DJNZ R0, READY_D_MIDDLE
    DJNZ R2, READY_D_OUTER
    POP 02H
    POP 01H
    POP 00H
    RET

MODE_SCROLL_DELAY:
    ; Approximately 0.28 seconds at 11.0592 MHz.
    PUSH 00H
    PUSH 01H
    PUSH 02H
    MOV R2, #02H
MODE_SCROLL_D_OUTER:
    MOV R0, #0FFH
MODE_SCROLL_D_MIDDLE:
    MOV R1, #0FFH
    DJNZ R1, $
    DJNZ R0, MODE_SCROLL_D_MIDDLE
    DJNZ R2, MODE_SCROLL_D_OUTER
    POP 02H
    POP 01H
    POP 00H
    RET

